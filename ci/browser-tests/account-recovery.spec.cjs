const {test,expect}=require('@playwright/test');
const {randomUUID}=require('node:crypto');
test('contractor can recover a password and homeowner can recover private request access',async({page})=>{
  const key=randomUUID().replace(/-/g,'');
  const created=await page.request.post('/__ci/recovery-fixture/'+key);
  expect(created.status()).toBe(200);const emails=await created.json();
  await page.goto('/contractor/login');await page.getByRole('link',{name:'Forgot password?'}).click();
  await page.getByLabel('Email address',{exact:true}).fill(emails.contractor);
  await page.getByRole('button',{name:'Email reset link',exact:true}).click();
  await expect(page.locator('body')).toContainText('If an eligible account or request matches');
  const reset=await (await page.request.get('/__ci/recovery-mailbox/'+key+'/contractor')).json();
  await page.goto(reset.path);
  await page.getByLabel('New password (at least 12 characters)',{exact:true}).fill('new-synthetic-ci-password');
  await page.getByLabel('Confirm new password',{exact:true}).fill('new-synthetic-ci-password');
  await page.getByRole('button',{name:'Save new password',exact:true}).click();
  await expect(page).toHaveURL(/\/contractor\/login$/);
  await page.getByLabel('Email address',{exact:true}).fill(emails.contractor);
  await page.getByLabel('Password',{exact:true}).fill('new-synthetic-ci-password');
  await page.getByRole('button',{name:'Sign In',exact:true}).click();
  await expect(page).toHaveURL(/\/contractor\/dashboard$/);
  expect((await page.request.get(reset.path)).status()).toBe(400);
  await page.goto('/request-access');await page.getByLabel('Email address',{exact:true}).fill(emails.consumer);
  await page.getByRole('button',{name:'Email access link',exact:true}).click();
  const access=await (await page.request.get('/__ci/recovery-mailbox/'+key+'/consumer')).json();
  await page.goto(access.path);await expect(page.getByLabel('Password',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Open my request status',exact:true}).click();
  await expect(page).toHaveURL(/\/request-status$/);await expect(page.locator('body')).toContainText('Mold Remediation');
  expect((await page.request.get(access.path)).status()).toBe(400);
});
